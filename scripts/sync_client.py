#!/usr/bin/env python3
"""Generate the shared scaffolding in every engine notebook from client.py.

    scripts/sync_client.py             # rewrite the generated cells in each <engine>/<engine>_notebook.py
    scripts/sync_client.py --check     # exit 1 if any notebook is out of date (for CI)

client.py is the source of truth. Each notebook holds two generated cells, identical in every engine, so it
also runs on its own, where client.py is not available:

- `setup`: the hidden `with app.setup` block. It is client.py minus its docstring and `__all__`, imports
  included, plus AUTORUN. Everything it defines is visible to every cell without being passed in, so the
  notebook's own cells use `os`, `time`, `requests`, ... from it and must not import them again.
- `helpers`: a collapsed list of the helpers' signatures and docstring summaries, plus a warning when
  MOTH_API_KEY is unset. Inserted right after `setup` if the notebook doesn't have it yet.

The notebook needs only a `with app.setup(hide_code=True):` block to start from; everything else in the two
cells is replaced on every run.
"""

import ast
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

SETUP = '''\
with app.setup(hide_code=True):
    # cell: setup
    # Shared scaffolding, generated from client.py by scripts/sync_client.py: edit client.py, not this block.
    # Everything defined here (the API helpers and their imports) is visible to every cell.
__CLIENT__

    AUTORUN = os.environ.get("MOTH_AUTORUN") == "1"  # headless exports: run every cell without pressing buttons'''

HELPERS = '''\
@app.cell(hide_code=True)
def _(mo):
    # cell: helpers
    # Generated by scripts/sync_client.py. Lists the API helpers from their own signatures and docstrings.
    import inspect as _inspect

    _summary = lambda f: _inspect.getdoc(f).partition("\\n\\n")[0]  # docstring's first paragraph
    _docs = "\\n".join(f"{f.__name__}{_inspect.signature(f)}\\n    {_summary(f)}" for f in (__NAMES__))
    _helpers = mo.accordion({"API helpers (`__NAMES__`), defined in the hidden setup cell": mo.plain_text(_docs)})
    _missing_key = mo.callout(mo.md(
        "`MOTH_API_KEY` is not set, so the cells that call the engine will fail. "
        "Create a key on the Atlas **API keys** page, export it, and restart the kernel."), kind="warn")
    mo.vstack([_missing_key, _helpers]) if not os.environ.get("MOTH_API_KEY") else _helpers
    return'''


def generated():
    src = (ROOT / "client.py").read_text()
    lines, drop, names = src.splitlines(), set(), []
    for node in ast.parse(src).body:
        text = isinstance(node, ast.Expr) and isinstance(node.value, ast.Constant) and isinstance(node.value.value, str)
        dunder = isinstance(node, ast.Assign) and getattr(node.targets[0], "id", "") == "__all__"
        if dunder:
            names = ast.literal_eval(node.value)
        if text or dunder:
            drop.update(range(node.lineno - 1, node.end_lineno))
    body = "\n".join(("    " + l) if l.strip() else "" for i, l in enumerate(lines) if i not in drop).strip("\n")
    return SETUP.replace("__CLIENT__", body), HELPERS.replace("__NAMES__", ", ".join(names))


def span(node):
    # Line range of a top-level statement, decorators included (0-based, end exclusive).
    return min([node.lineno] + [d.lineno for d in getattr(node, "decorator_list", [])]) - 1, node.end_lineno


def sync(path):
    text = path.read_text()
    lines = text.splitlines()
    setup = helpers = None
    for node in ast.parse(text).body:
        if isinstance(node, ast.With) and "app.setup" in ast.unparse(node.items[0].context_expr):
            setup = span(node)
        elif isinstance(node, ast.FunctionDef) and "    # cell: helpers" in lines[span(node)[0]:span(node)[1]]:
            helpers = span(node)
    if setup is None:
        sys.exit(f"{path.relative_to(ROOT)}: `with app.setup(hide_code=True):` block not found")
    new_setup, new_helpers = (s.splitlines() for s in generated())
    if helpers:  # replace the later cell first so the earlier span stays valid
        lines[helpers[0]:helpers[1]] = new_helpers
        lines[setup[0]:setup[1]] = new_setup
    else:
        lines[setup[0]:setup[1]] = new_setup + ["", ""] + new_helpers
    return "\n".join(lines) + "\n"


def main():
    check = "--check" in sys.argv[1:]
    stale = []
    for nb in sorted(ROOT.glob("*/*_notebook.py")):
        updated = sync(nb)
        if updated != nb.read_text():
            stale.append(nb)
            if not check:
                nb.write_text(updated)
    names = ", ".join(str(n.relative_to(ROOT)) for n in stale)
    if check and stale:
        sys.exit(f"out of date: {names}. Run scripts/sync_client.py")
    print(f"updated: {names}" if stale else "notebooks already match client.py")


if __name__ == "__main__":
    main()
