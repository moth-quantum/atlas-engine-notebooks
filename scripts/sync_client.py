#!/usr/bin/env python3
"""Copy client.py into every engine notebook, and generate the helper reference shown there.

    scripts/sync_client.py             # rewrite the generated blocks in each <engine>/<engine>_notebook.py
    scripts/sync_client.py --check     # exit 1 if any notebook is out of date (for CI)

client.py is the source of truth. Each notebook holds two generated blocks, so it also runs on its own,
where client.py is not available:

  * `client.py`      in the hidden `moth client` cell: the code, minus its imports and `__all__`.
                     Imports the notebook's `imports` cell already provides are the parameters of that
                     cell's `def _(...)`; the script drops them and keeps any other client-only import.
  * `client api`     in the visible `client-api` cell: a table of the functions in client.py's `__all__`.
"""

import ast
import inspect
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CODE = ("    # >>> client.py (generated by scripts/sync_client.py; edit client.py, not this block)", "    # <<< client.py")
DOCS = ("    # >>> client api (generated by scripts/sync_client.py from client.py)", "    # <<< client api")


def bound(node):
    return {(a.asname or a.name).split(".")[0] for a in node.names}


def code_block(provided):
    src = (ROOT / "client.py").read_text()
    lines, drop = src.splitlines(), set()
    for node in ast.parse(src).body:
        text = isinstance(node, ast.Expr) and isinstance(node.value, ast.Constant) and isinstance(node.value.value, str)
        dunder = isinstance(node, ast.Assign) and getattr(node.targets[0], "id", "") == "__all__"
        imp = isinstance(node, (ast.Import, ast.ImportFrom)) and bound(node) & provided
        if imp and not bound(node) <= provided:
            sys.exit(f"client.py line {node.lineno}: imports {sorted(bound(node))} but the notebook provides only some of them")
        if text or dunder or imp:
            drop.update(range(node.lineno - 1, node.end_lineno))
    kept = [l for i, l in enumerate(lines) if i not in drop]
    body = "\n".join(("    " + l) if l.strip() else "" for l in kept)
    body = re.sub(r"\n{4,}", "\n\n\n", body).strip("\n")
    return f"{CODE[0]}\n{body}\n{CODE[1]}"


def docs_block():
    tree = ast.parse((ROOT / "client.py").read_text())
    names = next(ast.literal_eval(n.value) for n in tree.body if isinstance(n, ast.Assign) and n.targets[0].id == "__all__")
    funcs = {n.name: n for n in tree.body if isinstance(n, ast.FunctionDef)}
    rows = []
    for name in names:
        fn = funcs[name]
        doc = " ".join((ast.get_docstring(fn) or "").split("\n\n")[0].split()).replace("|", "\\|")
        rows.append(f"    | `{name}({ast.unparse(fn.args)})` | {doc} |")
    table = "\n".join(rows)
    return f'''{DOCS[0]}
    mo.md(r"""
    ## Moth client

    The helpers below are defined in the hidden `moth client` cell and can be used in any cell.

    | function | what it does |
    |---|---|
{table}

    Set `MOTH_API_KEY` (and optionally `MOTH_API_BASE`) in the environment.
    """)
{DOCS[1]}'''


def replace(text, markers, new, path):
    i, j = text.find(markers[0]), text.find(markers[1])
    if i < 0 or j < i:
        sys.exit(f"{path.relative_to(ROOT)}: markers not found: {markers[0].strip()}")
    return text[:i] + new + text[j + len(markers[1]):]


def sync(path):
    text = path.read_text()
    m = re.search(r"def _\(([^)]*)\):\n\s+# cell: moth client", text)
    if not m:
        sys.exit(f"{path.relative_to(ROOT)}: `# cell: moth client` cell not found")
    provided = {p.strip() for p in m.group(1).split(",") if p.strip()}
    text = replace(text, CODE, code_block(provided), path)
    return replace(text, DOCS, docs_block(), path)


def main():
    check = "--check" in sys.argv[1:]
    stale = []
    for nb in sorted(ROOT.glob("*/*_notebook.py")):
        updated = sync(nb)
        if updated != nb.read_text():
            stale.append(nb)
            if not check:
                nb.write_text(updated)
    names = ", ".join(str(n.relative_to(ROOT)) for n in stale)
    if check and stale:
        sys.exit(f"out of date: {names}. Run scripts/sync_client.py")
    print(f"updated: {names}" if stale else "notebooks already match client.py")


if __name__ == "__main__":
    main()
