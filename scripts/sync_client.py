#!/usr/bin/env python3
"""Copy client.py into the `moth client` cell of every engine notebook.

    scripts/sync_client.py             # rewrite the generated block in each <engine>/<engine>_notebook.py
    scripts/sync_client.py --check     # exit 1 if any notebook is out of date (for CI)

client.py is the source of truth. Each notebook holds a copy between the markers below, so it also
runs when opened on its own, where client.py is not available.
"""

import ast
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BEGIN = "    # >>> client.py (generated by scripts/sync_client.py; edit client.py, not this block)"
END = "    # <<< client.py"


def block():
    src = (ROOT / "client.py").read_text()
    lines = src.splitlines()
    doc = ast.parse(src).body[0]
    if isinstance(doc, ast.Expr) and isinstance(doc.value, ast.Constant) and isinstance(doc.value.value, str):
        lines = lines[doc.end_lineno:]  # the module docstring documents the import, not the cell
    body = "\n".join(("    " + l) if l.strip() else "" for l in lines).strip("\n")
    return f"{BEGIN}\n{body}\n{END}"


def sync(path, new):
    s = path.read_text()
    i, j = s.find(BEGIN), s.find(END)
    if i < 0 or j < i:
        sys.exit(f"{path.relative_to(ROOT)}: markers not found; add the begin/end comments inside the `moth client` cell")
    return s[:i] + new + s[j + len(END):]


def main():
    check = "--check" in sys.argv[1:]
    new, stale = block(), []
    for nb in sorted(ROOT.glob("*/*_notebook.py")):
        updated = sync(nb, new)
        if updated != nb.read_text():
            stale.append(nb)
            if not check:
                nb.write_text(updated)
    names = ", ".join(str(n.relative_to(ROOT)) for n in stale)
    if check and stale:
        sys.exit(f"out of date: {names}. Run scripts/sync_client.py")
    print(f"updated: {names}" if stale else "notebooks already match client.py")


if __name__ == "__main__":
    main()
